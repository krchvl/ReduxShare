const BLACKBOARD_SYMBOLS: Record<string, string> = {
  C: "ℂ",
  F: "𝔽",
  H: "ℍ",
  N: "ℕ",
  P: "ℙ",
  Q: "ℚ",
  R: "ℝ",
  Z: "ℤ",
};

const LATEX_TEXT_COMMANDS = /\\(?:text|mathrm|textrm|operatorname|mbox|textbf|textit)\{([^{}]*)\}/g;
const LATEX_FRACTION = /\\frac\s*\{([^{}]*)\}\s*\{([^{}]*)\}/g;
const LATEX_ROOT = /\\sqrt\s*\{([^{}]*)\}/g;
const LATEX_COMMAND = /\\([a-zA-Z]+)/g;
const LATEX_SPACING = /\\([,;:!])/g;
const LATEX_ESCAPED_CHAR = /\\([%&_#$])/g;

export function convertLatexTokensToSymbols(value: string): string {
  if (!value.includes("\\")) {
    return value;
  }

  let result = value.replace(/\\[[(]/g, "").replace(/\\[\])]/g, "");
  result = result.replace(
    /\\mathbb\{([A-Z])\}/g,
    (match, letter: string) => BLACKBOARD_SYMBOLS[letter] ?? match,
  );
  result = result.replace(LATEX_TEXT_COMMANDS, "$1");
  result = result.replace(LATEX_FRACTION, "$1/$2");
  result = result.replace(LATEX_ROOT, "√$1");
  result = result.replace(LATEX_COMMAND, (match, name: string) =>
    Object.hasOwn(LATEX_SYMBOLS, name) ? LATEX_SYMBOLS[name] : match,
  );
  result = result.replace(LATEX_SPACING, " ");
  result = result.replace(LATEX_ESCAPED_CHAR, "$1");

  return result;
}
